pub fn by_id(id: &str) -> Option<&'static Format> {
    FORMATS.iter().find(|f| f.id == id)
}

/// 按类别列出格式。
pub fn by_kind(kind: Kind) -> Vec<&'static Format> {
    FORMATS.iter().filter(|f| f.kind == kind).collect()
}

