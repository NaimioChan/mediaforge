//! 内置格式表。
//!
//! 71 个目标格式，分四类。字段全部是 ffmpeg 概念，不含界面依赖。
//! 编码器候选链按优先级排列，运行期用能力清单过滤出第一个真正可用的。

use serde::Serialize;

/// 媒体大类，决定转换管线与界面分组。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    Video,
    Audio,
    Image,
    Subtitle,
}

impl Kind {
    pub fn label(self) -> &'static str {
        match self {
            Kind::Video => "视频",
            Kind::Audio => "音频",
            Kind::Image => "图像",
            Kind::Subtitle => "字幕",
        }
    }
}

/// 需要专用参数管线的格式。其余走 `Pipeline::Default`。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Pipeline {
    /// 常规：按类别走通用参数。
    Default,
    /// 动图 GIF：palettegen / paletteuse 滤镜链。
    Gif,
    /// ICO：必须缩进 256 以内，且单帧 + `-update 1`。
    Ico,
    /// DV：靠 `-target pal-dv` / `ntsc-dv` 让 ffmpeg 自己约束尺寸与采样率。
    Dv,
    /// MXF：dnxhd + 48 kHz PCM，尺寸对齐 1920×1080。
    Mxf,
    /// MicroDVD：当前 ffmpeg 构建没有该编码器，由本程序直接写文本。
    MicroDvdText,
    /// SBV：ffmpeg 没有 SBV 复用器，由本程序直接写文本。
    SbvText,
}

/// 一个输出格式的静态描述。
#[derive(Debug)]
pub struct Format {
    /// 稳定标识。
    pub id: &'static str,
    pub name: &'static str,
    pub kind: Kind,
    /// 输出扩展名，含点。
    pub ext: &'static str,
    /// 优先使用的复用器；空表示按扩展名推断。
    pub muxer: &'static str,
    /// 默认视频编码器候选，按优先级。
    pub video_encoders: &'static [&'static str],
    /// 用户可手动切换的视频编码器。
    pub video_alternatives: &'static [&'static str],
    pub audio_encoders: &'static [&'static str],
    pub audio_alternatives: &'static [&'static str],
    /// 容器是否支持多帧（动图）。
    pub animated: bool,
    pub pipeline: Pipeline,
    /// 面向用户的一句说明。
    pub notes: &'static str,
}

